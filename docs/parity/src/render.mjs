import { EPICS } from './dsl.mjs';

const GROUPS = [
  ['menu.app', 'Application menu'], ['menu.file', 'File menu'], ['menu.edit', 'Edit menu'], ['menu.para', 'Paragraph menu'],
  ['menu.format', 'Format menu'], ['menu.view', 'View menu'], ['menu.themes', 'Themes menu'], ['menu.window', 'Window menu'],
  ['menu.help', 'Help menu'], ['menu.state', 'Menu state'], ['ctx.', 'Context menus'], ['tools.table', 'Table tools'], ['tools.code', 'Code tools'],
  ['tools.math', 'Math tools'], ['tools.diagram', 'Diagrams'], ['images.', 'Images'], ['pref.', 'Preferences'], ['sidebar.', 'Sidebar & outline'],
  ['export.', 'Export / print / import'], ['syntax.', 'Markdown syntax options'], ['beh.core', 'Behaviors — editor core'],
  ['beh.files', 'Behaviors — files & windows'], ['beh.settings', 'Behaviors — settings'], ['beh.clip', 'Behaviors — clipboard'],
  ['ui.', 'Generic UI'], ['oos.', 'Out of scope'],
];
const ICON = { owned: 'owned', partial: '**partial**', missing: '**missing**', oos: 'out-of-scope' };
const esc = (s) => String(s).replace(/\|/g, '\\|');

export function renderMarkdown({ inv, summary, obligations }) {
  const c = summary.inventory;
  const L = summary.ledger.summary;
  const byId = new Map(obligations.map((o) => [o.id, o]));
  const lines = [];
  const p = (s = '') => lines.push(s);
  p('# Typora → Margin parity inventory');
  p();
  p('> Generated by `node docs/parity/src/build.mjs` — edit `docs/parity/src/*.mjs`, not this file.');
  p();
  p('Clean-room inputs only: the interface extract `typora-re/parity-spec.md` (281 menu titles, 527 panel labels, 98 bridge command names — no code), the prose behavior analysis `typora-re/sections/*.md`, and Margin\'s own source. Every spec label is attached to exactly the surfaces that need it (the build fails on any uncovered or unknown label), so this table is a complete, de-duplicated partition of the spec.');
  p();
  p('## Coverage');
  p();
  p('| | surfaces |');
  p('|---|---|');
  p(`| total | ${c.total} |`);
  p(`| owned (implemented) | ${c.owned} (with a named passing test: ${c.verified_by_test}) |`);
  p(`| partial | ${c.partial} |`);
  p(`| missing | ${c.missing} |`);
  p(`| out of scope | ${c.oos} |`);
  p(`| of which Margin extensions (beyond Typora, not parity) | ${c.margin_extensions ?? 0} |`);
  p();
  p(`REA ledger \`${summary.ledger.ledger_id}\` (closure \`${summary.ledger.closure_digest.slice(0, 16)}…\`): status **${summary.ledger.status}**; ` + L.by_status.filter((x) => x.count).map((x) => `${x.key} ${x.count}`).join(', ') + '.');
  p();
  p(`REA coverage boundary \`margin.typora-parity\`: status **${summary.coverage.status}**; ${summary.coverage.claims_qualified_by_controlled_replay}/${summary.coverage.claims_total} claims qualified by controlled-replay verifier Evidence. Reasons: ` + Object.entries(summary.coverage.reason_counts).map(([k, v]) => `${k} ${v}`).join(', ') + '.');
  p();
  p('Verifier runs (REA `capture_process_scenario`, controlled-replay/observed): ' + Object.entries(summary.verifier_runs).map(([k, v]) => `${k} exit ${v.exit}`).join(', ') + '. See `rea/summary.json`.');
  p();
  p('### Why nothing is REA-"verified" (and what would change that)');
  p();
  p('- **Original authority.** The ledger requires the original behaviour to be characterized by `shipped-artifact`/observed (static) or runtime Evidence. Under clean-room rules the only allowed inputs are prose, so every review record is `analyst-inference`/`inferred`; every obligation keeps the `static-only` diagnostic. Closing it needs a dirty-room observation exported as Evidence and handed over as an opaque record.');
  p('- **Proof predicate.** Fixture/verifier proof must be a `rea.reconstruction-proof` record from `verify_reconstruction_obligations`; REA 6.5.0 exposes no public tool that emits it. Our verifier runs are genuine `rea.process-capture` records, so bindings stay `implemented` with `weak-fixture-authority`/`weak-verifier-authority`.');
  p(`- **Auto-derived candidates.** The ${L.by_status.find((x) => x.key === 'unknown').count} \`unknown\` ledger obligations are generated by REA from the verifier process captures themselves (\"Captured packaged-process lifecycle\"): the ledger cannot tell a reconstruction's test run from an observation of the original, so it opens original-behaviour candidates for them. They keep the ledger status at \`unknown\` and are not product surfaces.`);
  p('- **Rust suite.** `cargo test` (src-tauri) ran 94 tests, 2 failed (`watch_live_tests::moved_in_and_moved_out`, `watch_live_tests::own_saves_in_watched_folder` on macOS); no surface uses it as its verifier.');
  p('- **Coverage evaluator** accepts controlled-replay captures, so owned surfaces with a named passing test qualify there; package proofs lack `clean-install`.');
  p();
  p('## Epics (open work)');
  p();
  p('| epic | priority | open surfaces |');
  p('|---|---|---|');
  for (const [id, e] of Object.entries(EPICS)) {
    const open = inv.surfaces.filter((s) => s.e === id && (s.status === 'missing' || s.status === 'partial'));
    p(`| \`${id}\` ${e.title} | P${e.p} | ${open.length} |`);
  }
  p();
  for (const [prefix, name] of GROUPS) {
    const rows = inv.surfaces.filter((s) => s.id.startsWith(prefix));
    if (!rows.length) continue;
    p(`## ${name}`);
    p();
    p('| id | surface | status | prio | owner | verifier | spec items |');
    p('|---|---|---|---|---|---|---|');
    for (const s of rows) {
      const o = byId.get(s.id);
      const owner = s.ownerFile ? `\`${s.ownerFile}\` ${'`' + esc(s.ownerAnchor) + '`'}` : '—';
      const ver = s.verifier ? `\`${s.verifierFile}\` › ${esc(s.verifierTitle)}` : 'none';
      const n = (s.A?.length ?? 0) + (s.B?.length ?? 0) + (s.C?.length ?? 0);
      const extra = (s.x ? ` — **Margin extension (not parity):** ${esc(s.x)}` : '') + (s.why ? ` — ${esc(s.why)}` : s.note ? ` — ${esc(s.note)}` : '');
      p(`| \`${s.id}\` | ${esc(s.title)}${extra} | ${ICON[s.status]}${s.x ? ' (extension)' : ''} | ${o.priority ?? ''} | ${owner} | ${ver} | ${n} |`);
    }
    p();
  }
  p('## Native bridge commands → surfaces');
  p();
  p('| bridge command | surface |');
  p('|---|---|');
  for (const cmd of inv.spec.C) p(`| \`${cmd}\` | ${inv.surfaces.filter((s) => (s.C ?? []).includes(cmd)).map((s) => '`' + s.id + '`').join(', ')} |`);
  p();
  return lines.join('\n');
}
